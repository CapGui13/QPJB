'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const fixture=require('./quizz-l02-10-approved-additions.json');
const html=fs.readFileSync(path.join(__dirname,'..','quizz.html'),'utf8');
const m=html.match(/<script id="training-data" type="application\/json">([\s\S]*?)<\/script>/);
assert.ok(m,'Quiz data embedded');
const data=JSON.parse(m[1]); const xs=data.exercises;
assert.ok(xs.length>=1263,'Au moins 1 253 historiques + 10 L02');
assert.equal(new Set(xs.map(x=>x.id)).size,xs.length,'unique identifiers');
assert.equal(data.themes.length,22,'22 existing topics');
assert.match(data.description,new RegExp(String(xs.length)+' QCM'),'updated total');
const fnv=(s)=>{let h=2166136261;for(let i=0;i<s.length;i++)h=Math.imul(h^s.charCodeAt(i),16777619)>>>0;return h.toString(16).padStart(8,'0');};
assert.equal(fnv(JSON.stringify(xs.slice(0,1253))),fixture.originalPrefixFnv1aUtf16,'1 253 historical exercises unchanged');
assert.deepEqual(xs.slice(1253,1263),fixture.additions,'the original 10 L02 reviewed exercises preserved exactly');
const val={A:4,R:3,D:2,V:1};
const suit={'♣':0,'♦':1,'♥':2,'♠':3,SA:4};
const rank=x=>x==='Passe'?-3:x==='Contre'?-2:x==='Surcontre'?-1:(()=>{const m=x.match(/^([1-7])(♣|♦|♥|♠|SA)$/);return m?(+m[1]-1)*5+suit[m[2]]:null})();
const existingHands=new Set(xs.slice(0,1253).map(x=>JSON.stringify(x.hand)));
const seen=new Set(xs.slice(0,1253).map(x=>JSON.stringify([x.hand,x.auction])));
for(const x of fixture.additions){
 assert.equal(x.theme,'chelem',x.id+' topic');
 assert.equal(x.hand.length,4,x.id+' four suits');
 assert.equal(x.hand.flat().length,13,x.id+' 13 cards');
 assert.deepEqual(x.hand.map(s=>s.length),x.shape,x.id+' shape');
 assert.equal(x.hand.flat().reduce((sum,c)=>sum+(val[c]||0),0),x.h,x.id+' H');
 assert.ok(x.hand.every(s=>s.length===new Set(s).size),x.id+' no repeated card in suit');
 assert.equal(x.choices.length,4,x.id+' choices');
 assert.equal(new Set(x.choices).size,4,x.id+' unique choices');
 assert.ok(x.choices.includes(x.answer),x.id+' answer');
 const ranks=x.choices.map(rank);assert.ok(ranks.every(Number.isInteger),x.id+' legal bids');
 assert.deepEqual(ranks,ranks.toSorted((a,b)=>a-b),x.id+' sorted bids');
 const last=x.auction.at(-1);assert.match(last,/^Partenaire\s*:/,x.id+' turn belongs to user');
 const m=last.match(/([1-7](?:♣|♦|♥|♠|SA))/);assert.ok(m,x.id+' last bid');
 assert.ok(x.choices.every(b=>rank(b)<0||rank(b)>rank(m[1])),x.id+' bids strictly more expensive');
 assert.ok(!x.context.includes(x.answer),x.id+' prompt does not reveal answer');
 assert.ok(x.explain.trim().length>25,x.id+' corrected explanation');
 assert.ok(!existingHands.has(JSON.stringify(x.hand)),x.id+' new hand');
 const key=JSON.stringify([x.hand,x.auction]);assert.ok(!seen.has(key),x.id+' unique hand and sequence');seen.add(key);
}
assert.ok(!xs.some(x=>x.id==='SEF-L02-E-04'),'ambiguous E-04 deliberately excluded');
console.log('PASS | L02 V4.114: 1 253 historical exercises unchanged + 10 reviewed = 1 263; additional later exercises: '+(xs.length-1263));
