'use strict';
const assert=require('node:assert/strict');
const {rank}=require('../quizz-coherence-m4p-a-rank.js'),adapter=require('./coherence-concrete-m4p-a-adapter.cjs');
const q=(id,h,shape=[4,3,3,3])=>({id,theme:'mineur',difficulty:1,caseFamily:id,h,shape,auction:['Partenaire : 1♦'],answer:'1♠'});
const a=q('a',9),b=q('b',6),c=q('c',9),d=q('d',10);
const exercises=[a,b,c,d],metadataById=Object.fromEntries(exercises.map(x=>[x.id,{concept:'mineur.base',stage:1,minSession:1,requires:[]}]));
const clean=id=>({id,result:'correct',assisted:false,hadFreeError:false});
const event=(session,id)=>({mode:'parcours',session,answers:Array.from({length:10},()=>clean(id))});
const ctx={session:3,category:'discovery',baselineId:'a',candidates:[a,b,d],exercises,metadataById,selected:[c],history:{journal:[event(1,'c'),event(2,'c')]}};
assert.equal(rank(ctx)[0].id,'b');
assert.equal(rank({...ctx,policy:'R'})[0].id,'b');
assert.deepEqual(rank({...ctx,session:21}),[]);
assert.deepEqual(rank({...ctx,session:2}),[]);
assert.deepEqual(rank({...ctx,forcedReason:'rappel_erreur_aide'}),[]);
assert.deepEqual(rank({...ctx,category:'weakness'}),[]);
assert.deepEqual(rank({...ctx,history:{...ctx.history,active:{}}}),[]);
assert.deepEqual(rank({...ctx,history:{journal:[event(2,'c')]}}),[]);
const bad=event(2,'c');bad.answers[0].assisted=true;
assert.deepEqual(rank({...ctx,history:{journal:[event(1,'c'),bad]}}),[]);
assert.deepEqual(rank({...ctx,selected:[],policy:'L'}),[]);
assert.deepEqual(rank({...ctx,candidates:[a,c]}),[]);
const rows=[{q:a,v:10},{q:b,v:9}];assert.equal(adapter.pick(ctx,rows,a),a);
assert.equal(adapter.pick(ctx,[{q:a,v:10},{q:b,v:10}],a,20),b);
assert.equal(adapter.pick({...ctx,session:21},[{q:a,v:10},{q:b,v:10}],a),a);
assert.equal(rank({...ctx,candidates:[a,{...b,answer:'1SA'}]}).length,0);
assert.equal(rank({...ctx,candidates:[a,{...b,difficulty:2}]}).length,0);
assert.equal(rank({...ctx,candidates:[a,{...b,caseFamily:'c'}]}).length,0);
assert.deepEqual(rank({...ctx,policy:'T'}),[]);
const sameFamily={...b,caseFamily:'a'};
assert.equal(rank({...ctx,policy:'T',candidates:[a,sameFamily]})[0].id,'b');
assert.deepEqual(rank({...ctx,policy:'T',candidates:[a,sameFamily],history:{journal:[event(1,'c'),{...event(2,'d'),answers:Array.from({length:10},()=>({...clean('d'),assisted:true}))}]}}),[]);
console.log('20 assertions M4P-A PASS');
