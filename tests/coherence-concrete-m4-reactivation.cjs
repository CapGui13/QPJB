'use strict';
const assert=require('node:assert/strict'),m=require('../quizz-coherence-m4-reactivation.js'),b=require('../quizz-coherence-m4-contrast.js');
const q=(id,answer,h,shape,auction=[],theme='ouv')=>({id,answer,h,shape,auction,theme,caseFamily:id,difficulty:1});
const a=q('a','1♥',14,[4,5,2,2]),x=q('x','1♠',14,[5,4,2,2]),y=q('y','1♥',17,[3,5,3,2]);
const pass=q('p','Passe',7,[4,3,3,3]),minor=q('m','1♣',13,[4,3,3,3]);
const meta={a:{concept:'ouv.majeure'},x:{concept:'ouv.majeure'},y:{concept:'ouv.majeure'},p:{concept:'ouv.passe'},m:{concept:'ouv.mineure'}};
let n=0;const check=(v,msg)=>{assert.ok(v,msg);n++};
const ctx={session:3,candidates:[x,y],selected:[{exercise:a}],exercises:[a,x,y,pass,minor],metadataById:meta,category:'discovery',baselineId:'x',history:{journal:[{mode:'parcours',session:2,answers:[{id:'a',result:'correct'}]}]}};
check(m.rank(ctx)[0].delta<m.rank(ctx)[1].delta,'contraste utile');
check(m.rank({...ctx,session:1}).length===0,'S1 préservée');
check(m.rank({...ctx,history:{journal:[]}}).every(r=>r.delta===0),'absence de preuve');
check(m.rank({...ctx,category:'weakness'}).every(r=>r.delta===0),'rappel lacune');
check(m.rank({...ctx,history:{...ctx.history,micros:{'ouv:passe':{score:-1}}}}).every(r=>r.delta===0),'fragilité Passe S1–5');
check(m.rank({...ctx,forcedReason:'rappel_erreur_aide'}).length===0,'rappel explicite');
check(m.rank({...ctx,history:{active:{}}}).length===0,'reprise');
const debt={...ctx,session:15,candidates:[pass,minor],baselineId:'m',selected:[],category:'maintenance',objective:{concepts:['ouv.passe']},history:{journal:[{mode:'parcours',session:2,answers:[{id:'p',result:'wrong'}]},{mode:'parcours',session:14,answers:[{id:'m',result:'correct'}]}]}};
check(m.rank(debt)[0].delta>0,'dette fondamental même après erreur');
check(m.rank({...debt,objective:null})[0].delta===0,'pas de rappel imposé hors plan');
check(m.rank({...debt,priority:true})[0].delta===0,'priorité intacte');
check(m.rank({...debt,selected:[pass]})[0].delta===0,'un seul rappel');
check(m.rank({...debt,baselineId:'p'})[0].delta===0,'ne pas déloger un rappel ancien');
const snap=JSON.stringify(ctx);check(JSON.stringify(m.rank(ctx))===JSON.stringify(m.rank(ctx))&&JSON.stringify(ctx)===snap,'pureté');
check(b.rank(ctx).every(r=>r.delta>=-64&&r.delta<=16),'B bornée');
check(m.rank(ctx).every(r=>r.delta>=-36&&r.delta<=16&&r.reason),'C bornée');
console.log('M4 contrast/reactivation PASS',n);
