'use strict';
const assert=require('node:assert/strict');
const m=require('../quizz-coherence-m4-diversite.js');
let n=0;const check=(x,msg)=>{assert.ok(x,msg);n++};
const q=(id,answer,h,shape,auction=[],theme='ouv')=>({id,answer,h,shape,auction,theme,caseFamily:id,difficulty:1});
const a=q('a','1♥',14,[4,5,2,2]),b=q('b','1♠',14,[5,4,2,2]),c=q('c','1♥',17,[3,5,3,2]);
const meta={a:{concept:'ouv.majeure'},b:{concept:'ouv.majeure'},c:{concept:'ouv.majeure'}};
check(m.features(a,meta.a).near===m.features(b,meta.b).near,'miroir majeur');
check(m.features(a,meta.a).near!==m.features(c,meta.c).near,'contraste de force');
const x=q('x','1♣',13,[4,3,3,3]),y=q('y','1♣',13,[3,2,4,4]);
check(m.features(x,{concept:'ouv.mineure'}).decision!==m.features(y,{concept:'ouv.mineure'}).decision,'égalité distincte');
check(m.features(q('p','Passe',5,[4,3,3,3]),{concept:'ouv.passe'}).force!==m.features(q('r','Passe',11,[4,3,3,3]),{concept:'ouv.passe'}).force,'frontière Passe');
check(m.features(a,{concept:'sa1.texas'}).decision!==m.features(b,{concept:'sa1.texas'}).decision,'pas de miroir conventionnel');
const ctx={session:2,metadataById:meta,candidates:[b,c],selected:[{exercise:a}],exercises:[a,b,c],category:'discovery',history:{journal:[],entries:{}}};
const before=JSON.stringify(ctx),r=m.rank(ctx);
check(r[0].delta<r[1].delta,'préférence variante contrastée');
check(r.every(z=>['b','c'].includes(z.id)&&z.delta>=-44&&z.delta<=12&&z.reason),'bornes et IDs');
check(JSON.stringify(ctx)===before,'pureté');
check(JSON.stringify(m.rank(ctx))===JSON.stringify(r),'déterminisme');
check(m.rank({...ctx,forcedReason:'rappel_erreur_aide'}).length===0,'rappel explicite');
check(m.rank({...ctx,history:{active:{}}}).length===0,'reprise');
check(m.rank(null).length===0&&m.rank({}).length===0,'entrées absentes');
check(m.rank({...ctx,candidates:[b,b,c]}).length===2,'IDs uniques');
const recent={...ctx,selected:[],history:{journal:[{mode:'parcours',session:1,answers:[{id:'a',result:'correct'}]}]}};
check(m.rank(recent)[0].delta<0,'proximité déjà réussie');
check(m.rank({...recent,category:'weakness'})[0].delta===0,'fragilité protégée');
check(m.rank({...recent,history:{journal:[{mode:'parcours',session:1,answers:[{id:'a',result:'correct',assisted:true}]}]}})[0].delta===0,'aide non assimilée à preuve');
console.log('M4 unit PASS',n);
