'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),{createHash}=require('node:crypto');
const approved=require('./quizz-v491-approved-revisions.json');
const {normalizedPrefix}=require('./quizz-v488-approved-revisions.cjs');
const html=fs.readFileSync(path.join(__dirname,'..','quizz.html'),'utf8');
const m=html.match(/<script id="training-data" type="application\/json">([\s\S]*?)<\/script>/);
assert.ok(m,'Quiz JSON embedded');
const db=JSON.parse(m[1]),xs=db.exercises;
assert.equal(xs.length,1223,'1223 QCM preserved');
assert.equal(new Set(xs.map(x=>x.id)).size,1223,'unique identifiers');
assert.equal(db.themes.length,22,'22 themes');
assert.deepEqual(Object.keys(approved),['SEF-V49-005'],'one approved question');
const entry=approved['SEF-V49-005'],x=xs.find(x=>x.id==='SEF-V49-005');
assert.ok(x,'Quiz entry found');
assert.deepEqual(x,entry.after,'exact reviewed new quiz entry');
assert.equal(entry.before.answer,'1♥','historical Walsh answer');
assert.equal(x.answer,'1♦','SEF sans Walsh with 5 diamonds and 4 hearts');
assert.deepEqual(x.choices,entry.before.choices,'four original choices unchanged');
assert.deepEqual(x.auction,entry.before.auction,'auction unchanged');
assert.deepEqual(x.hand,entry.before.hand,'hand unchanged');
assert.equal(x.h,7,'H points unchanged');
assert.equal(x.hand.flat().reduce((n,c)=>n+({A:4,R:3,D:2,V:1}[c]||0),0),7);
assert.equal(x.hand.flat().length,13,'13 cards');
assert.deepEqual(x.hand.map(c=>c.length),x.shape,'shape intact');
assert.equal(x.sourceOriginalAnswer20261105V491,'1♥','prior answer archived');
assert.equal(x.sourceOriginalExplain20261105V491,entry.before.explain,'prior explanation archived');
assert.equal(x.sourceOriginalContext20261105V491,entry.before.context,'prior context archived');
assert.equal(x.pedagogicalReview20261105V491.previousAnswer,'1♥','review trace');
assert.equal(x.pedagogicalReview20261105V491.approvedAnswer,'1♦','review trace');
assert.doesNotMatch(x.context+x.explain+x.difficultyReason,/Walsh/i,'no Walsh in live teaching text');
assert.ok(html.includes("'SEF-V49-005':'sef-2026-11-05-v491-sef-mineure-cinquieme-sans-walsh'"),
 'only this changed answer has a new progression revision');
const baseline=require('./quizz-baseline-1223-gitsha.json');
const payload=JSON.stringify(normalizedPrefix(xs,baseline.count));
const sha=createHash('sha1').update('blob '+Buffer.byteLength(payload,'utf8')+'\0'+payload,'utf8').digest('hex');
assert.equal(sha,baseline.gitBlobSha,'all historical QCM recovered exactly except individually approved changes');
console.log('PASS | V4.91: one correction 1♥ -> 1♦, exact historical snapshots and targeted revision');
