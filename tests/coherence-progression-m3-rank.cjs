'use strict';
const assert=require('node:assert/strict');
const M=require('../quizz-pedagogie-avancee.js');
assert.equal(M.schema,'QPJB_PEDAGOGIE_V1');
assert.equal(M.phase,'avancee');
const q=(id,caseFamily=id)=>({id,caseFamily});
const meta={a:{concept:'chelem.cles',stage:0,requires:[]},b:{concept:'chelem.cles',stage:0,requires:[]},
 c:{concept:'chelem.controles',stage:0,requires:[]},d:{concept:'chelem.blackwood.suite',stage:3,requires:[{concept:'chelem.cles',minExposure:1}]}};
const ev=(session,id,family,result='correct',assisted=false,hadFreeError=false,mode='parcours')=>({mode,session,answers:[{id,family,result,assisted,hadFreeError}]});
const freeze=o=>{if(o&&typeof o==='object'){Object.freeze(o);for(const v of Object.values(o))freeze(v)}return o};
const ctx=freeze({session:66,candidates:[q('a','fa'),q('b','fb'),q('c'),q('d'),q('missing'),q('b','fb')],metadataById:meta,
 history:{journal:[ev(5,'a','fa'),ev(40,'a','fa','correct',true),ev(64,'a','fa','correct',false,true,'consolidation')]},selected:[],category:'maintenance'});
const deltas=x=>Object.fromEntries(M.rank(x).map(r=>[r.id,r]));
assert.deepEqual(M.rank({...ctx,session:65}),[]);
assert.deepEqual(M.rank({...ctx,session:20}),[]);
assert.deepEqual(M.rank({...ctx,candidates:[]}),[]);
const a=deltas(ctx);
assert(a.a.delta>0);
assert(a.b.delta>a.a.delta);
assert(a.b.reason.includes('transfert-autre-famille'));
assert(a.d.delta<0);
assert(!a.missing);
assert(M.rank(ctx).every(x=>Number.isInteger(x.delta)&&x.delta>=-100&&x.delta<=100));
assert.equal(M.rank(ctx).filter(x=>x.id==='b').length,1);
assert.deepEqual(M.rank(ctx),M.rank(ctx));
const contrast=deltas({...ctx,selected:[{exercise:q('a')} ]});
assert(contrast.c.delta>0);
assert(contrast.a.delta<a.a.delta);
const old=deltas({...ctx,history:{entries:{a:{assessment:{result:'correct',assisted:false,lastSession:4}}},journal:[]}});
assert(old.d.delta<0,'ancienne évaluation ne constitue pas une preuve autonome');
const assisted=deltas({...ctx,history:{journal:[ev(5,'a','fa','correct',true),ev(6,'b','fb','correct',false,true)]}});
assert(assisted.d.delta<0);
const proof=deltas({...ctx,history:{journal:[ev(5,'a','fa'),ev(6,'b','fb')]}});
assert(!proof.d,'preuve autonome observée, pas de malus de dépendance');
const consolidation=deltas({...ctx,history:{journal:[ev(64,'a','fa','correct',false,false,'consolidation')]}});
assert(consolidation.d.delta<0);
assert(!consolidation.a);
assert(M.rank({...ctx,session:181}).length>0);
console.log('M3 unit: phase, petit pool, pureté, bornes, transfert, aides, consolidation, contrastes OK');
