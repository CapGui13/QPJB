'use strict';
const assert=require('node:assert/strict'),P=require('../quizz-revision-policy.js');
const q=(id,f,h,d=1)=>({id,caseFamily:f,hand:[[h]],difficulty:d});
const qs=[q('a','f1','A'),q('b','f2','B'),q('c','f1','C'),q('d','f3','A'),q('e','f4','E',3)];
const metadata=Object.fromEntries(qs.map(q=>[q.id,{concept:'x'}]));
const event=(session,id,result='correct',assisted=false,hadFreeError=false,mode='parcours')=>({session,mode,answers:[{id,result,assisted,hadFreeError}]});
const prep=(session,journal,candidates=qs,entries={})=>P.prepare({state:{completed:session,journal,entries},metadata,exercises:qs,candidates});
const w=prep(1,[event(1,'a','wrong')]);
assert.equal(w.schedule[0].interval,1);assert.deepEqual(w.recall(qs).map(x=>x.id),['b']);
assert.equal(w.rank(qs[0]),null);assert.equal(w.rank(qs[1]).reason,'rappel_nouvelle_situation');
assert.equal(w.rank(qs[1],{x:1}),null);
assert.equal(prep(1,[event(1,'a','wrong')],[qs[0]]).rank(qs[0]).exact,true);
assert.equal(prep(1,[event(1,'a','correct',true)]).schedule[0].interval,1);
assert.equal(prep(1,[event(1,'a','correct',false,true)]).schedule[0].interval,1);
assert.equal(prep(3,[event(1,'a')]).schedule[0].interval,3);
assert.equal(prep(4,[event(1,'a'),event(3,'a')]).schedule[0].interval,3);
assert.equal(prep(4,[event(1,'a'),event(3,'b')]).schedule[0].interval,8);
assert.equal(prep(12,[event(1,'a'),event(3,'b'),event(11,'a')]).schedule[0].interval,18);
assert.equal(prep(12,[event(1,'a'),event(3,'b'),event(11,'a','wrong')]).schedule[0].interval,1);
assert.equal(prep(2,[event(1,'a'),event(1,'b','wrong')]).schedule[0].interval,1);
assert.equal(prep(2,[event(1,'a','correct',false,false,'consolidation')]).schedule.length,0);
assert.equal(prep(4,[],qs,{a:{result:'correct',lastSession:0,streak:50}}).schedule[0].interval,3);
assert.equal(prep(4,[],qs,{a:{result:'correct',lastSession:0,assessment:null}}).schedule.length,0);
assert.equal(prep(1,[event(1,'a','wrong')],[qs[1]]).rank(qs[0]),null);
const state={completed:1,journal:[event(1,'a','wrong')],entries:{}},before=JSON.stringify(state);
P.prepare({state,metadata,exercises:qs,candidates:qs});assert.equal(JSON.stringify(state),before);
console.log('M2 unit assertions OK');
