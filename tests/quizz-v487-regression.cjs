'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),{createHash}=require('node:crypto');
const html=fs.readFileSync(path.join(__dirname,'..','quizz.html'),'utf8');
const m=html.match(/<script id="training-data" type="application\/json">([\s\S]*?)<\/script>/);
assert.ok(m,'Quiz SEF training-data found');
const db=JSON.parse(m[1]),xs=db.exercises,base=require('./quizz-baseline-1216-gitsha.json');
assert.equal(base.count,1216,'Protected V4.86 history');
assert.ok(xs.length>=1223,'1216 historical and 7 V4.87 exercises');
assert.equal(db.themes.length,22,'Themes unchanged');
const original=JSON.stringify(xs.slice(0,1216));
const sha=createHash('sha1').update('blob '+Buffer.byteLength(original,'utf8')+'\0'+original).digest('hex');
assert.equal(sha,base.gitBlobSha,'1216 QCM unchanged as serialized JSON');
const expected=[{"id":"SEF-V487-001","theme":"reponse_inter","answer":"3♣","h":12,"shape":[2,4,4,3]},{"id":"SEF-V487-002","theme":"reponse_inter","answer":"2♣","h":14,"shape":[2,3,4,4]},{"id":"SEF-V487-003","theme":"fortes","answer":"4SA","h":10,"shape":[3,3,4,3]},{"id":"SEF-V487-004","theme":"fortes","answer":"3♠","h":11,"shape":[3,3,3,4]},{"id":"SEF-V487-005","theme":"fortes","answer":"Passe","h":0,"shape":[3,3,4,3]},{"id":"SEF-V487-006","theme":"forcing","answer":"3♣","h":13,"shape":[3,4,3,3]},{"id":"SEF-V487-007","theme":"forcing","answer":"3♥","h":17,"shape":[3,5,4,1]}];
const cases=xs.slice(1216,1223);
assert.deepEqual(cases.map(x=>x.id),expected.map(x=>x.id),'Append-only V4.87 contiguous block');
const point={A:4,R:3,D:2,V:1},ord={'♣':0,'♦':1,'♥':2,'♠':3,SA:4};
const rank=s=>s==='Passe'?-3:s==='Contre'?-2:s==='Surcontre'?-1:(()=>{const m=s.match(/^([1-7])(♣|♦|♥|♠|SA)$/);return m?(Number(m[1])-1)*5+ord[m[2]]:null})();
assert.equal(new Set(xs.map(x=>x.id)).size,xs.length,'Unique exercise ids');
const seen=new Set(xs.slice(0,1216).map(x=>JSON.stringify([x.auction,x.hand])));
for(let i=0;i<cases.length;i++){
 const x=cases[i],e=expected[i];
 assert.equal(x.theme,e.theme,x.id+' theme');
 assert.equal(x.answer,e.answer,x.id+' correct answer');
 assert.equal(x.h,e.h,x.id+' H');
 assert.deepEqual(x.shape,e.shape,x.id+' distribution');
 assert.equal(x.hand.length,4,x.id+' suits');
 assert.equal(x.hand.flat().length,13,x.id+' 13 cards');
 assert.deepEqual(x.hand.map(s=>s.length),x.shape,x.id+' cards shape');
 for(const s of x.hand)assert.equal(new Set(s).size,s.length,x.id+' unique card ranks');
 assert.equal(x.hand.flat().reduce((n,c)=>n+(point[c]||0),0),x.h,x.id+' points');
 assert.equal(x.choices.length,4,x.id+' four answers');
 assert.equal(new Set(x.choices).size,4,x.id+' unique answers');
 assert.ok(x.choices.includes(x.answer),x.id+' one correct answer among four');
 assert.ok(x.choices.every(a=>rank(a)!==null),x.id+' valid calls');
 assert.deepEqual(x.choices.map(rank),x.choices.map(rank).toSorted((a,b)=>a-b),x.id+' economical call order');
 const bid=x.auction.map(z=>z.match(/:\s*([1-7](?:♣|♦|♥|♠|SA))/)).filter(Boolean).at(-1)?.[1];
 assert.ok(bid&&x.choices.every(a=>a==='Passe'||a==='Contre'||a==='Surcontre'||rank(a)>rank(bid)),x.id+' calls higher than current contract');
 assert.ok(x.context.length>=230&&x.explain.length>=100,x.id+' explanation and context');
 assert.ok(!x.whyNot&&!x.takeaway,x.id+' only correct explanation');
 assert.ok(Number.isInteger(x.difficulty)&&x.difficulty>=1&&x.difficulty<=5,x.id+' level');
 const key=JSON.stringify([x.auction,x.hand]);assert.ok(!seen.has(key),x.id+' no full duplicate');seen.add(key);
}
console.log('PASS | V4.87: 1216 historiques intacts, 7 ajouts vérifiés, cartes/points/enchères corrects');
