'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),{createHash}=require('node:crypto');
const approved=require('./quizz-v499-approved-revisions.json');
const {normalizedPrefix}=require('./quizz-v488-approved-revisions.cjs');
const html=fs.readFileSync(path.join(__dirname,'..','quizz.html'),'utf8');
const m=html.match(/<script id="training-data" type="application\/json">([\s\S]*?)<\/script>/);
assert.ok(m,'Embedded Quiz SEF training data');
const db=JSON.parse(m[1]),xs=db.exercises;
assert.equal(xs.length,1223,'QCM count unchanged');
assert.equal(db.themes.length,22,'Theme count unchanged');
assert.equal(new Set(xs.map(x=>x.id)).size,1223,'All IDs remain unique');
assert.deepEqual(Object.keys(approved),['SEF-V479-016'],'Only the approved individual case');
const row=approved['SEF-V479-016'],x=xs.find(y=>y.id==='SEF-V479-016');
assert.deepEqual(x,row.after,'Exact approved post-arbitration QCM');
for(const k of ['answer','choices','hand','h','shape','auction','theme','difficulty','caseFamily'])
 assert.deepEqual(x[k],row.before[k],k+' remains unchanged');
assert.equal(x.answer,'2SA'); assert.equal(x.h,12);
assert.deepEqual(x.shape,[3,3,4,3]);
assert.equal(x.hand.flat().reduce((n,c)=>n+({A:4,R:3,D:2,V:1}[c]||0),0),12,'Hand has exactly 12 H');
assert.match(x.context,/fit d'au moins huit cartes/);
assert.match(x.context,/envisager la manche/);
assert.match(x.explain,/12 H/);
assert.match(x.explain,/espoir de manche/);
assert.match(x.explain,/2SA est un relais positif/);
assert.match(x.explain,/sa mineure et la force/);
assert.match(x.explain,/accord de paire Multi-Landy/);
assert.equal(x.sourceOriginalContext20261105V499,row.before.context);
assert.equal(x.sourceOriginalExplain20261105V499,row.before.explain);
assert.equal(x.sourceOriginalDifficultyReason20261105V499,row.before.difficultyReason);
const historical=require('./quizz-baseline-1223-gitsha.json');
const original=JSON.stringify(normalizedPrefix(xs,historical.count));
const sha=createHash('sha1').update('blob '+Buffer.byteLength(original,'utf8')+'\0'+original,'utf8').digest('hex');
