'use strict';
const assert=require('node:assert/strict');
const F=require('../scripts/parcours-v2-pilot.cjs');
const AB=require('../scripts/parcours-v2-lecons-ab.cjs');
const AD=require('../scripts/parcours-v2-comprehension-ad.cjs');
const VIEW=require('../scripts/parcours-v2-apercu-comprehension-ad.cjs');
const catalog=F.loadCatalog(),before=JSON.stringify(catalog);
const annotations=F.loadAnnotations();
assert.equal(catalog.length,1523);
assert.equal(annotations.size,79);
const r=AD.validate(AB.LESSONS,catalog);
assert.equal(r.schema,'QPJB_AD_COMPREHENSION_EDITORIAL_1');
assert.equal(r.items,6);
assert.equal(r.lessons,2);
assert.deepEqual(r.counts,{rubensohl:3,michaels:3});
assert.equal(r.sourceQuestions,5);
assert.ok(r.checkpoints>=12);
assert.ok(r.sourceAnchors>=10);
assert.equal(r.policy.type,'OPEN_ENDED_REFORMULATION');
assert.equal(r.policy.noQcmAdded,true);
assert.equal(r.policy.noAutomatedCorrection,true);
assert.equal(r.policy.scored,false);
assert.equal(r.policy.answersPersisted,false);
assert.equal(r.policy.publicRuntimeWired,false);
assert.equal(r.policy.readinessInferred,false);
assert.equal(r.policy.studentValidationDone,false);
assert.equal(r.policy.teacherApprovalRequired,true);
const ids=AD.PROMPTS.map(x=>x.id);
assert.equal(new Set(ids).size,6);
assert.deepEqual(ids,['AD-R01','AD-R02','AD-R03','AD-M01','AD-M02','AD-M03']);
for(const x of AD.PROMPTS){
 const lesson=AB.LESSONS.find(l=>l.id===x.lesson);
 assert.ok(lesson);
 for(const source of x.sources)assert.ok(lesson.sourceIds.includes(source));
 for(const anchor of x.anchors)assert.ok(JSON.stringify(lesson).includes(anchor));
 assert.ok(x.prompt.length>25);
 assert.ok(x.teacherIndicators.every(c=>c.length>25));
 assert.ok(x.misunderstanding.length>25);
 assert.ok(!Object.hasOwn(x,'choice'));
 assert.ok(!Object.hasOwn(x,'answer'));
 assert.ok(!Object.hasOwn(x,'grade'));
}
const wrongLesson=JSON.parse(JSON.stringify(AB.LESSONS));
wrongLesson[0].blocks[1].body='Définition absente du cours';
assert.throws(()=>AD.validate(wrongLesson,catalog),/ancrage dans la leçon/);
const wrongCatalog=catalog.slice();
const idx=wrongCatalog.findIndex(q=>q.id==='SEF-V486-022');
wrongCatalog[idx]={...wrongCatalog[idx],answer:'2SA'};
assert.throws(()=>AD.validate(AB.LESSONS,wrongCatalog),/accord source changé/);
const summary=AD.report();
assert.equal(summary.tasks.length,6);
assert.equal(summary.notStudentResults,true);
assert.equal(summary.decisionsNotAutomatic,true);
const html=VIEW.render(catalog);
assert.ok(html.startsWith('<!doctype html>'));
assert.equal((html.match(/<article data-lesson=/g)||[]).length,2);
assert.equal((html.match(/<textarea /g)||[]).length,6);
assert.equal((html.match(/class="task"/g)||[]).length,6);
assert.equal((html.match(/<details>/g)||[]).length,6);
assert.equal((html.match(/class="clear"/g)||[]).length,6);
assert.ok(html.includes('data-lesson="rubensohl"'));
assert.ok(html.includes('data-lesson="michaels"'));
assert.ok(html.includes('aucune réponse n’est enregistrée ou notée'));
assert.ok(html.includes('Repères de discussion pour l’enseignant'));
assert.ok(html.includes('Landy'));
assert.ok(html.includes('au moins 5–5'));
for(const id of ids){
 assert.ok(html.includes('id="'+id+'"'));
 assert.ok(html.includes('data-for="'+id+'"'));
}
assert.ok(!html.includes('__ARTICLES__')&&!html.includes('__NAV__'));
assert.ok(!html.includes('localStorage'));
assert.ok(!html.includes('sessionStorage'));
assert.ok(!html.includes('indexedDB'));
assert.ok(!html.includes('fetch('));
assert.ok(!html.includes('XMLHttpRequest'));
assert.ok(!html.includes('<form'));
assert.ok(!html.includes('type="radio"'));
assert.ok(!html.includes('type="submit"'));
assert.ok(!html.includes('<script src='));
for(const q of catalog.filter(q=>AB.LESSONS.some(l=>l.sourceIds.includes(q.id)))){
 assert.ok(!html.includes(q.context),'Question original not allowed '+q.id);
 assert.ok(!html.includes(q.explain),'Original correction not allowed '+q.id);
}
const scriptStart=html.lastIndexOf('<script>')+'<script>'.length;
const scriptEnd=html.indexOf('</script>',scriptStart);
assert.ok(scriptStart>7&&scriptEnd>scriptStart);
assert.doesNotThrow(()=>new Function(html.slice(scriptStart,scriptEnd)));
assert.deepEqual(JSON.stringify(catalog),before);
console.log('QPJB AD PASS : 6 open-ended non-scored source-anchored prompts, zero QCM or answer persistence');
