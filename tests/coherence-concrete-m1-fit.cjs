'use strict';
const assert=require('node:assert/strict');
const C=require('../quizz-coherence-m1-fit.js');
const q=(id,answer,shape=[3,3,4,3],theme='majeur',auction=['Partenaire : 1♠'])=>({id,answer,shape,theme,auction,difficulty:1,caseFamily:id});
const pass=q('p','Passe'),support=q('s','2♠'),supportH=q('h','2♥',[2,3,4,4],'majeur',['Partenaire : 1♥']);
assert.equal(C.fitRole(pass),'passe-avec-fit');assert.equal(C.fitRole(support),'support-5-3');assert.equal(C.fitRole(supportH),'support-5-3');
for(const wrong of [q('a','1SA'),q('b','2♥'),q('c','2♠',[4,3,3,3]),q('d','2♠',[3,3,4,3],'ouv'),q('e','2♠',[3,3,4,3],'majeur',['Partenaire : 1♠','Adversaire : 2♣'])])assert.equal(C.fitRole(wrong),null);
const orig=q('o','1♥',[3,5,3,2],'mineur',['Partenaire : 1♣']),seen=q('m','1♠',[4,3,3,3],'mineur',['Partenaire : 1♦']);
const metadataById={o:{concept:'mineur.base',stage:0},m:{concept:'mineur.base',stage:0},p:{concept:'majeur.soutien',stage:0},s:{concept:'majeur.soutien',stage:0},h:{concept:'majeur.soutien',stage:0}};
const r=(id,family)=>({id,family,result:'wrong',assisted:false,hadFreeError:false});
const row=session=>({mode:'parcours',session,answers:Array.from({length:10},(_,i)=>r(i%2?'s':'h',i%2?'s':'h'))});
const flags={due:false,bad:false,novelFamily:true,firstConcept:false,overdueCore:false};
const ctx={session:3,candidates:[orig,pass,support],selected:[{exercise:seen}],metadataById,history:{journal:[row(1),row(2)]},category:'weakness',flagsById:{o:flags,p:flags,s:flags}};
const rank=[{q:orig,v:100},{q:pass,v:99},{q:support,v:98}];
assert.equal(C.compose(ctx,rank)?.id,'s');
assert.equal(C.compose(ctx,rank.slice(0,2)),null);
const selectedSupport={...ctx,selected:[...ctx.selected,{exercise:supportH}]};
assert.equal(C.compose(selectedSupport,rank)?.id,'p');
assert.equal(C.compose({...selectedSupport,selected:[...selectedSupport.selected,{exercise:pass}]},rank),null);
assert.equal(C.plan(ctx).fitObjective.supportSelected,false);
assert.equal(C.plan(selectedSupport).fitObjective.supportSelected,true);
console.log('M1 V4 true 5–3 support, pass with fit, and semantic distinction PASS');
