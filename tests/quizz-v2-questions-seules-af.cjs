'use strict';
const assert=require('node:assert/strict');
const F=require('../scripts/parcours-v2-pilot.cjs');
const AF=require('../scripts/parcours-v2-questions-seules-af.cjs');
const P=require('../quizz-parcours.js');
const catalog=F.loadCatalog(),annotations=F.loadAnnotations();
const original=JSON.stringify(catalog);
assert.equal(catalog.length,1523);
assert.equal(annotations.size,79);
assert.equal(AF.POLICY.noLessons,true);
assert.equal(AF.POLICY.teacherConfirmationRequired,false);
assert.equal(AF.POLICY.automaticRubensohlIntroSession,35);
assert.equal(AF.POLICY.publicRuntimeWired,false);
assert.equal(P.INTRO.rubensohl,34);
assert.equal(catalog.filter(q=>q.theme==='rubensohl').length,49);
const pool=AF.visibleQuestions(catalog);
assert.strictEqual(pool,catalog);
assert.ok(pool.some(AF.requiresRubensohl));
assert.throws(()=>AF.run(catalog,annotations,{teacherConfirmedBeforeSession:40}),/manuel supprimé/);
assert.throws(()=>AF.run(catalog,annotations,{sessions:0}),/séances/);
const before=AF.run(catalog,annotations,{sessions:34,seed:13,profile:'balanced'});
assert.equal(before.advancedThemeQuestions,0);
assert.equal(before.metrics.questionCount,340);
const automatic=AF.run(catalog,annotations,{sessions:45,seed:13,profile:'balanced'});
assert.equal(automatic.status,'SIMULATED_PATH_ONLY_NO_STUDENT_DATA');
assert.equal(automatic.lessonsIncluded,0);
assert.equal(automatic.questionsPerSession,10);
assert.equal(automatic.originalCatalogSize,1523);
assert.equal(automatic.automaticRubensohlIntroSession,35);
assert.ok(automatic.advancedThemeQuestions>0);
assert.equal(automatic.metrics.questionCount,450);
assert.equal(automatic.metrics.repeatedFamilySessions,0);
assert.ok(automatic.metrics.uniqueFamilies>=430);
assert.ok(automatic.sessions.slice(0,34).flat().every(q=>!AF.requiresRubensohl(q)));
assert.ok(automatic.sessions[34].some(q=>q.theme==='rubensohl'));
assert.ok(automatic.sessions.every(deck=>deck.length===10&&deck.every(q=>catalog.includes(q))));
const reference=F.simulateV2(catalog,annotations,{sessions:45,seed:13,profile:'balanced'});
assert.deepEqual(automatic.sessions.map(deck=>deck.map(q=>q.id)),
 reference.sessions.map(deck=>deck.map(q=>q.id)));
assert.equal(automatic.metrics.review.scheduledDueRecalls,
 reference.metrics.revision.scheduledDueRecalls);
assert.equal(JSON.stringify(catalog),original);
console.log('QPJB AF PASS : Rubensohl éligible automatiquement séance 35 ; 10 QCM sans leçon, sans verrou manuel ; tirages identiques à V2-F.');
