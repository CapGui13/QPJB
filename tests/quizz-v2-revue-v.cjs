'use strict';
/* Phase V : protection des huit sources, sans modifier le Quiz SEF */
const assert=require('node:assert/strict');
const F=require('../scripts/parcours-v2-pilot.cjs');
const V=require('../scripts/parcours-v2-revue-v.cjs');
const catalog=F.loadCatalog();
const annotations=F.loadAnnotations();
const original=JSON.stringify(catalog);
const report=V.inspect(catalog);
assert.equal(report.schema,'QPJB_V2_V_CASES_SOURCE_1');
assert.equal(report.status,'READ_ONLY_ORIGINAL_SOURCE');
assert.equal(report.catalogQuestions,1523);
assert.equal(report.reviewedCases,8);
assert.equal(report.originalSourcesUnchanged,true);
assert.equal(report.answerModified,false);
assert.equal(report.publicRuntimeWired,false);
assert.equal(report.pedagogicalMasteryInferred,false);
assert.equal(new Set(Object.values(V.SOURCE_GROUPS).flat()).size,8);
const contrast=report.groups.oneClubFiveDiamondsFourMajor;
assert.deepEqual(contrast.map(q=>q.answer),['1♥','1♦','1♠','1♦']);
assert.deepEqual(contrast.map(q=>q.h),[7,14,8,13]);
assert.ok(contrast.every(q=>q.shape[2]===5));
assert.ok(contrast.every(q=>q.auction.length===1&&q.auction[0]==='Partenaire : 1♣'));
assert.equal(report.groups.oneDiamondNoMajor.length,2);
assert.equal(report.groups.oneNoTrumpPass.length,2);
assert.equal(JSON.stringify(catalog),original,'Revue ne doit pas réécrire le catalogue');
const fake=catalog.slice();
const idx=fake.findIndex(q=>q.id==='SEF-V426-002');
fake[idx]={...fake[idx],answer:'1♠'};
assert.throws(()=>V.inspect(fake),/Source différente/);
const sims=F.simulateV2(catalog,annotations,{sessions:5,seed:13});
const snapshot=sims.sessions.map(deck=>deck.map(q=>q.id));
const stateBefore=JSON.stringify(sims.state);
const exposure=V.exposures(sims.sessions,report);
assert.equal(Object.keys(exposure.occurrences).length,8);
assert.ok(Object.values(exposure.occurrences).every(v=>v.every(s=>s>=1&&s<=5)));
assert.deepEqual(sims.sessions.map(deck=>deck.map(q=>q.id)),snapshot);
assert.equal(JSON.stringify(sims.state),stateBefore);
console.log('QPJB V2 V PASS : 8 mains originales, contraste 5♦+4M en 4 QCM, aucune mutation');
